/* ---------- Auto-fill salary when staff is selected ---------- */
function adm_fillSalary() {
  const sel = document.getElementById('ps_staff');
  const opt = sel.options[sel.selectedIndex];
  const salary = parseInt(opt.dataset.salary) || 0;
  const grossInput = document.getElementById('ps_gross');
  if (grossInput && salary) {
    grossInput.value = salary;
  }
  adm_recalcPayslip();
}

/* ---------- Recalculate deductions live ---------- */
function adm_recalcPayslip() {
  const gross = parseInt(document.getElementById('ps_gross') ? document.getElementById('ps_gross').value : 0) || 0;
  const housing   = parseInt(document.getElementById('ps_housing')  ? document.getElementById('ps_housing').value  : 0) || 0;
  const transport = parseInt(document.getElementById('ps_transport')? document.getElementById('ps_transport').value : 0) || 0;
  const meal      = parseInt(document.getElementById('ps_meal')     ? document.getElementById('ps_meal').value      : 0) || 0;
  const bonus     = parseInt(document.getElementById('ps_bonus')    ? document.getElementById('ps_bonus').value     : 0) || 0;

  const totalGross = gross + housing + transport + meal + bonus;

  // PAYE (simplified Nigeria personal income tax bands — monthly)
  let paye = 0;
  const monthly = totalGross;
  if (monthly > 500000) paye = Math.round(monthly * 0.24);
  else if (monthly > 300000) paye = Math.round(monthly * 0.19);
  else if (monthly > 200000) paye = Math.round(monthly * 0.15);
  else if (monthly > 100000) paye = Math.round(monthly * 0.11);
  else paye = Math.round(monthly * 0.07);

  const pension = Math.round(gross * 0.08);
  const nhf     = Math.round(gross * 0.025);
  const totalDeduct = paye + pension + nhf;
  const netPay  = totalGross - totalDeduct;

  const set = (id, val) => { const el = document.getElementById(id); if (el) el.textContent = val; };
  set('ps_paye_disp',    pay_fmt(paye));
  set('ps_pension_disp', pay_fmt(pension));
  set('ps_nhf_disp',     pay_fmt(nhf));
  set('ps_deduct_disp',  pay_fmt(totalDeduct));
  set('ps_net_disp',     pay_fmt(netPay));
}

/* ---------- Save payslip ---------- */
function adm_savePayslip() {
  const schoolId = AUTH.current.schoolId || 'sch_brightlights';
  const staffId  = document.getElementById('ps_staff').value;
  const period   = document.getElementById('ps_period').value.trim();
  const gross    = parseInt(document.getElementById('ps_gross').value) || 0;

  if (!staffId) { toast('Please select a staff member', 'danger'); return; }
  if (!period)  { toast('Please enter a period', 'danger'); return; }
  if (!gross)   { toast('Please enter the gross salary', 'danger'); return; }

  const housing   = parseInt(document.getElementById('ps_housing').value)   || 0;
  const transport = parseInt(document.getElementById('ps_transport').value) || 0;
  const meal      = parseInt(document.getElementById('ps_meal').value)      || 0;
  const bonus     = parseInt(document.getElementById('ps_bonus').value)     || 0;
  const totalGross = gross + housing + transport + meal + bonus;

  let paye = 0;
  if (totalGross > 500000)      paye = Math.round(totalGross * 0.24);
  else if (totalGross > 300000) paye = Math.round(totalGross * 0.19);
  else if (totalGross > 200000) paye = Math.round(totalGross * 0.15);
  else if (totalGross > 100000) paye = Math.round(totalGross * 0.11);
  else                          paye = Math.round(totalGross * 0.07);

  const pension = Math.round(gross * 0.08);
  const nhf     = Math.round(gross * 0.025);
  const totalDeduct = paye + pension + nhf;
  const netPay  = totalGross - totalDeduct;

  const staff = DB.find('teachers', staffId);
  const sel   = document.getElementById('ps_staff');
  const opt   = sel.options[sel.selectedIndex];

  const payslip = {
    id:          uid('psl'),
    schoolId,
    staffId,
    period,
    grossPay:    totalGross,
    allowances:  { housing, transport, meal, bonus },
    deductions:  { paye, pension, nhf, total: totalDeduct },
    netPay,
    bankName:    opt.dataset.bank    || (staff && staff.bank ? staff.bank.name    : ''),
    bankAccount: opt.dataset.account || (staff && staff.bank ? staff.bank.account : ''),
    status:      'pending',
    paidAt:      null,
    createdAt:   now()
  };

  DB.insert('payslips', payslip);

  // Notify the staff member
  DB.insert('notifications', {
    id:        uid('not'),
    userId:    staffId,
    title:     `Payslip Ready — ${period}`,
    body:      `Your payslip for ${period} is ready. Net pay: ${pay_fmt(netPay)}.`,
    type:      'info',
    read:      false,
    timestamp: now(),
    link:      { view: 'tch_payslip' }
  });

  document.getElementById('modalBackdrop').click();
  APP.render();
  toast(`Payslip generated for ${staff ? staff.name : 'staff'} — ${period}`, 'success');
}

/* ---------- Mark payslip as paid ---------- */
function adm_markPayslipPaid(id) {
  const p = DB.find('payslips', id);
  const staff = DB.find('teachers', p.staffId);
  confirm(`Mark this payslip (${p.period} · ${pay_fmt(p.netPay)}) as paid?`, () => {
    DB.update('payslips', id, { status: 'paid', paidAt: now() });
    DB.insert('notifications', {
      id:        uid('not'),
      userId:    p.staffId,
      title:     `Salary Paid — ${p.period}`,
      body:      `Your net salary of ${pay_fmt(p.netPay)} for ${p.period} has been disbursed to your bank account.`,
      type:      'success',
      read:      false,
      timestamp: now(),
      link:      { view: 'tch_payslip' }
    });
    APP.render();
    toast(`Payslip marked as paid for ${staff ? staff.name : 'staff'}`, 'success');
  });
}

/* ---------- Delete payslip ---------- */
function adm_deletePayslip(id) {
  const p = DB.find('payslips', id);
  const staff = DB.find('teachers', p.staffId);
  confirm(`Delete this payslip (${p.period} · ${staff ? staff.name : ''})? This cannot be undone.`, () => {
    DB.remove('payslips', id);
    APP.render();
    toast('Payslip deleted', 'info');
  }, { yesLabel: 'Delete', danger: true });
}
